-- 024 — the decision record, and eleven decisions that already existed in the wrong place.
--
-- Every other human act in this system has an audit table. Approving has one. Reviewing has
-- one. Declaring a completion false has one. Handing a component to another machine has one,
-- and it refuses without a stated reason. DECIDING — the act the whole factory line exists to
-- serve — has had none, which is why `sandbox.system_change` sat at zero rows while eleven
-- `--sidebar-rail-*` tokens were proposed, approved, and authored into no file under
-- `tokens/`. A decision that is not recorded cannot be required, and cannot be reused.
--
-- ── This is a migration, not a schema design ───────────────────────────────────────
-- `proposedDarkRailTokens` in `sandbox/src/data/rail-sidebar.ts` already IS the precedent
-- table, written in the wrong place: eleven rows, each pairing an origin value with a chosen
-- value, under a proposed token name, with the usage it serves. It has been doing this table's
-- job in a TypeScript array that nothing can query, nothing can require, and no other
-- component can ever inherit from. The columns below are its shape, plus the two fields it
-- never had: who decided, and why.
--
-- Moving it also closes a gap the audit found in the corpus itself. Six of the nine B rows —
-- B-2, B-3, B-4, B-7, B-8, B-9 — carry `afterVar = null` and, in its place, the prose
-- `afterNote: "Resolved by Q2 and the approved Color token lab candidate."` That sentence is
-- an IOU pointing at a decision this database has never held. Their proposed token existed
-- only as `proposedVar` in the array, so the corpus could not answer "what token does B-2
-- propose" — which is exactly what a `token.authored` requirement (026) has to read. After
-- this migration every one of the nine has its token as a real column value, and the six are
-- promoted from `register = 'confirm'` to `'decide'`.
--
-- ── Nothing here was retyped, and no rationale was invented ────────────────────────
-- The values below were GENERATED by bundling the real module with esbuild and reading the
-- array — never transcribed by eye. CLAUDE.md checklist item 18 exists because a
-- fabricated-but-plausible value passes typecheck, build and smoke test and only fails under
-- close inspection against the real source.
--
-- `rationale` is NOT NULL and no row was given a manufactured one. Four tokens carry their own
-- `proposalNote`, written at the time the decision was revised — that IS the rationale, and it
-- is used verbatim. The other seven each have a B row whose `review_prompt` states the
-- constraint the value had to satisfy; that is used instead, and it is already covered against
-- drift by `db/verify-review-prompt-fidelity.mjs`. Every one of the eleven therefore carries a
-- real sentence somebody wrote about that specific value.
--
-- ── What is asserted rather than proven, said once, plainly ────────────────────────
-- `decided_by` is caller-supplied, exactly like `author_agent_id` and the machine name, and
-- for the same reason: all three machines share one `app_rw` principal, so the database cannot
-- prove who is on the other end. It is recorded as `owner` for all eleven, because the source
-- material attributes them to owner review sessions ("Q2 approved", "Approved: …") without
-- naming a person, and inventing one would be worse than the gap. `provenance` distinguishes
-- these reconstructed rows from anything recorded live afterwards, so no future reader has to
-- guess which is which. A named, timestamped, rationale-bearing record that is asserted is
-- still a very long way from zero.
--
-- ── disposition: all eleven are `authored`, and that is the finding ────────────────
-- Not one of the eleven resolves in `tokens/*.tokens.json` — verified by walking all three
-- token files and every nested group. Under the owner's own step 2 an authored value stays
-- blocked until the token exists, which is what 026 enforces. `reused` is the other half of
-- that rule and is not merely a placeholder: 13 further corpus rows propose tokens that DO
-- already resolve (`--accent`, `--border`, `--ring`, `--muted-foreground` and others), and
-- those are reuse decisions that belong in this table too. They are not seeded here because
-- this migration's contract is the array, and only the array — a wider sweep is a separate,
-- reviewable act.
-- ═══════════════════════════════════════════════════════════════════════════════════

CREATE TABLE sandbox.divergence_decision (
    decision_id       INT IDENTITY(1,1) PRIMARY KEY,
    component_id      INT           NOT NULL REFERENCES sandbox.component(component_id),
    -- Nullable on purpose: two of the eleven (`darkDividerSubtle`, `darkActiveHoverBg`) have
    -- no divergence row at all. They are real decisions with no row to hang from, which is
    -- itself worth being able to see — a decision table keyed strictly to divergences would
    -- have silently dropped them.
    divergence_id     INT           NULL     REFERENCES sandbox.divergence(divergence_id),
    concept           NVARCHAR(100) NOT NULL,
    usage_note        NVARCHAR(300) NULL,
    -- Origin's own value, and the value chosen instead. `_dark` is nullable because a decision
    -- that does not vary by mode has one value, not two; a colour in this project always has
    -- both, since the light/dark parity gate refuses anything else.
    origin_value      NVARCHAR(100) NULL,
    origin_value_dark NVARCHAR(100) NULL,
    chosen_value      NVARCHAR(100) NOT NULL,
    chosen_value_dark NVARCHAR(100) NULL,
    -- The token the decision lands in, when it lands in one. NULL for a decision about
    -- something other than a token (a structure, an element order, a behaviour).
    chosen_token      NVARCHAR(100) NULL,
    disposition       NVARCHAR(10)  NOT NULL
        CONSTRAINT ck_decision_disposition CHECK (disposition IN ('reused','authored')),
    rationale         NVARCHAR(MAX) NOT NULL
        CONSTRAINT ck_decision_rationale CHECK (LEN(LTRIM(RTRIM(rationale))) > 0),
    decided_by        NVARCHAR(100) NOT NULL,
    provenance        NVARCHAR(10)  NOT NULL
        CONSTRAINT ck_decision_provenance CHECK (provenance IN ('recorded','migrated')),
    decided_at        DATETIME2     NOT NULL CONSTRAINT df_decision_decided_at DEFAULT SYSUTCDATETIME(),
    created_at        DATETIME2     NOT NULL CONSTRAINT df_decision_created_at DEFAULT SYSUTCDATETIME()
);
GO

CREATE INDEX ix_decision_divergence ON sandbox.divergence_decision(divergence_id);
CREATE INDEX ix_decision_token      ON sandbox.divergence_decision(chosen_token);
GO

