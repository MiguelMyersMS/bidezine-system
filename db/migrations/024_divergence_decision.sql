-- ── the six rows the register backfill could not see ──────────────────────────────
-- 023 registered a row `decide` when its own `visual` named an after-value. These six name
-- none — the prose IOU sits where the value should be — so they were left `confirm`, which is
-- the register that asks only for evidence and a review. They are decisions, and now there is
-- a row proving it: promote exactly the rows this migration just gave a decision to.
UPDATE  d
SET     d.register   = 'decide',
        d.updated_at = SYSUTCDATETIME()
FROM    sandbox.divergence d
WHERE   d.register = 'confirm'
  AND   EXISTS (SELECT 1 FROM sandbox.divergence_decision dd WHERE dd.divergence_id = d.divergence_id);
GO

-- ── append-only ───────────────────────────────────────────────────────────────────
-- Writes go through `usp_record_decision` (025) and nowhere else, which is how `evidence` and
-- `review` are already protected (019). The DENY is what makes the procedure the only door:
-- an unbroken ownership chain lets the procedure insert on the caller's behalf, while a direct
-- INSERT from `app_rw` is refused — so the mandatory rationale and the ownership check cannot
-- be walked around by writing to the table instead.
GRANT SELECT ON OBJECT::sandbox.divergence_decision TO app_rw;
GRANT SELECT ON OBJECT::sandbox.divergence_decision TO agent_rw;
GRANT SELECT ON OBJECT::sandbox.divergence_decision TO runner_evidence;
DENY  INSERT, UPDATE, DELETE ON OBJECT::sandbox.divergence_decision TO app_rw;
DENY  INSERT, UPDATE, DELETE ON OBJECT::sandbox.divergence_decision TO agent_rw;
DENY  INSERT, UPDATE, DELETE ON OBJECT::sandbox.divergence_decision TO runner_evidence;
GO
